def run_full_evaluation(ideas_json: str, prompt: str = "", target_audience: str = "general", style: str = "") -> dict:
    """?????Layer1 ???? + Layer2 LLM??"""
    from app.services import evaluator
    import json as _json
    
    result = {"layer1": None, "layer2": None, "passed": False}
    
    # Layer 1: regex check
    try:
        ideas = _json.loads(ideas_json)
        result["layer1"] = evaluator.evaluate_creative_ideas(ideas)
    except Exception:
        result["layer1"] = {"passed": False, "issues": ["JSON parse failed"]}
    
    # Layer 2: LLM judge
    result["layer2"] = judge_creative_ideas(ideas_json, target_audience)
    
    result["passed"] = result["layer1"]["passed"] and result["layer2"].get("passed", False)
    
    if prompt:
        prompt_eval = judge_prompt_quality(prompt, style)
        result["prompt_eval"] = prompt_eval
        result["passed"] = result["passed"] and prompt_eval.get("passed", False)
    
    return result

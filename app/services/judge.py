def _get_judge_client():
    import os
    api_key = os.environ.get("DEEPSEEK_API_KEY", "")
    if not api_key:
        try:
            from app.config import config
            api_key = config.app.get("deepseek_api_key", "")
        except Exception:
            pass
    if not api_key:
        raise ValueError("DEEPSEEK_API_KEY not set")
    return OpenAI(api_key=api_key, base_url="https://api.deepseek.com/v1", timeout=30)


def judge_creative_ideas(ideas_json: str, target_audience: str = "general") -> dict:
    """? LLM ???????????"""
    client = _get_judge_client()
    
    prompt = f"""?????????????????????????????

??????1-5???
1. ????????????????
2. ??????????????"{target_audience}"
3. ??????????????AI????????
4. ??????????????????
5. ????????????????????

?????
{ideas_json}

?????JSON?
{{"scores": {{"brand_consistency": 4, "audience_match": 5, ...}}, "overall": 4.2, "comments": "????...", "passed": true}}

passed ? true ???? overall >= 3.0?"""

    try:
        resp = client.chat.completions.create(
            model="deepseek-chat",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=500,
        )
        text = resp.choices[0].message.content.strip()
        # Parse JSON
        if "```" in text:
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        result = json.loads(text)
        return {"success": True, **result}
    except Exception as e:
        logger.warning(f"LLM judge failed: {e}")
        return {"success": True, "passed": True, "overall": 3.0, "scores": {}, "comments": f"Judge unavailable: {e}"}


